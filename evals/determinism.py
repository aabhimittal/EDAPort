"""Determinism at scale: run many single-threaded tool calls, replay each one, report the match rate.

Spec acceptance: replay determinism >= 99% on single-threaded runs. Covers every tool that runs on host
binaries or the oss-tools image; add --orfs for single-threaded ORFS stages + OpenSTA on gcd/sky130hd.

    python evals/determinism.py [--orfs] [--out evals/determinism_results.md]
"""

import argparse
import collections
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from edaport.server.engine import Engine  # noqa: E402


def calls(e: Engine, orfs: bool):
    ctr = e.call("snapshot_import", path=str(ROOT / "examples/counter"))["design_ref"]
    src = e.store.read_file(ctr, "rtl/counter.v").decode()
    fixed = e.call("snapshot_write", design_ref=ctr, path="rtl/counter.v",
                   content=src.replace("(count > MAX)", "(count >= MAX)"))["design_ref"]
    phys = e.call("snapshot_import", path=str(ROOT / "examples/physical"))["design_ref"]
    for ref in (ctr, fixed):
        for seed in range(1, 21):
            yield "sim_run", dict(design_ref=ref, tb_ref="tb/tb_counter.sv", seed=seed)
        for seed in range(1, 4):
            yield "sim_run", dict(design_ref=ref, tb_ref="tb/tb_counter.sv", seed=seed, simulator="verilator",
                                  coverage=True)
            yield "sim_run", dict(design_ref=ref, tb_ref="tb/test_counter.py", top="counter", seed=seed)
        for tool in ("verilator", "iverilog"):
            yield "lint_run", dict(design_ref=ref, tool=tool)
        for lib in (None, "lib/demo.lib"):
            yield "synth_run", dict(design_ref=ref, top="counter", liberty_ref=lib)
        for mode, depth in (("bmc", 10), ("bmc", 20), ("prove", 10), ("cover", 10)):
            yield "formal_run", dict(design_ref=ref, sby_ref="formal/counter.sby", mode=mode, depth=depth)
    syn = e.call("synth_run", design_ref=fixed, top="counter", liberty_ref="lib/demo.lib")["design_ref"]
    for gold in (fixed, ctr):
        for seq in (3, 5):
            yield "equiv_run", dict(gold_ref=gold, gate_ref=syn, top="counter", seq=seq)
    for _ in range(3):
        yield "drc_run", dict(design_ref=phys, deck="demo.drc")
        yield "lvs_run", dict(design_ref=phys, layout="inv_layout.spice", schematic="inv_schematic.spice", top="inv")
    if orfs:
        ref = e.call("snapshot_import", path=str(ROOT / "examples/gcd_sky130hd"))["design_ref"]
        for stage in ("synth", "floorplan", "place", "cts", "grt", "route"):
            r = e.call("flow_run_stage", design_ref=ref, stage=stage, threads=1)
            yield None, r  # already executed: replay it as recorded
            ref = r["design_ref"]
        for pd in ("max", "min"):
            yield "sta_report_paths", dict(design_ref=ref, k=5, path_delay=pd, threads=1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--orfs", action="store_true")
    ap.add_argument("--out", default=str(ROOT / "evals/determinism_results.md"))
    a = ap.parse_args()
    os.environ.setdefault("EDAPORT_IMPORT_ROOTS", str(ROOT))
    e = Engine(tempfile.mkdtemp(prefix="edaport-det-"))
    total, matched, bad = collections.Counter(), collections.Counter(), []
    for tool, kw in calls(e, a.orfs):
        res = kw if tool is None else e.call(tool, **kw)
        if not res["ok"]:
            bad.append(f"{res['tool']} did not run: {res['error']}")
            continue
        rp = e.call("replay_run", run_id=res["run_id"])
        total[res["tool"]] += 1
        matched[res["tool"]] += bool(rp["match"])
        if not rp["match"]:
            bad.append(f"{res['tool']} {res['run_id']} digest mismatch")
    n, ok = sum(total.values()), sum(matched.values())
    lines = ["# Replay determinism (single-threaded)\n", "Generated by `python evals/determinism.py"
             + (" --orfs" if a.orfs else "") + f"`; tools: `EDAPORT_RUNNER={e.oss.kind}`.\n",
             "| tool | runs replayed | matched |", "|---|---:|---:|"]
    lines += [f"| `{t}` | {total[t]} | {matched[t]} |" for t in sorted(total)]
    lines += [f"| **total** | **{n}** | **{ok}** |", "", f"Determinism rate: {ok}/{n} = {ok / n:.1%}."]
    lines += [f"- {b}" for b in bad]
    Path(a.out).write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0 if ok == n and not bad else 1


if __name__ == "__main__":
    sys.exit(main())
